/**
 * Regenerates database/seed.sql from src/constants/*.ts (demo data).
 * Usage: npm run seed:generate
 * The seed contains NO passwords: demo users start with pw_hash = NULL and cannot sign in until
 * ADMIN_PASSWORD / DEMO_PASSWORD are provided at server start (see HowToSetup.md).
 */
import fs from 'node:fs';
import path from 'node:path';
import {
  INITIAL_COMPANIES, INITIAL_LICENSE_TYPES, INITIAL_LICENSE_NAMES, INITIAL_USERS, INITIAL_LICENSES,
  INITIAL_PAYMENT_LINKS, DEFAULT_MENU_PERMS, INITIAL_NOTIFICATION_CONFIG
} from '../src/constants/initialData';

const q = (v: unknown) => (v === undefined || v === null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const json = (v: unknown) => q(JSON.stringify(v));

// Demo recipients are placeholders - replace them in the Notification Center after install.
const cfg = JSON.parse(JSON.stringify(INITIAL_NOTIFICATION_CONFIG));
delete cfg.lastAutoRunAt; delete cfg.lastAutoRunDate; delete cfg.autoRunCountToday;
let n = 0;
for (const unit of Object.keys(cfg.recipients)) {
  n += 1;
  cfg.recipients[unit] = { emails: [`${unit.toLowerCase()}.compliance@example.com`], phones: [`88017000000${String(n).padStart(2, '0')}`] };
}

const out: string[] = [
  '-- BLMS demo seed data. GENERATED by scripts/generate-seed.ts - do not edit by hand.',
  '-- Applied automatically to an empty database (disable with AUTO_SEED=false).',
  '-- Contains no passwords. Demo users cannot sign in until a password is provided (see HowToSetup.md).',
  'BEGIN;'
];

const settings: Record<string, unknown> = {
  companies: INITIAL_COMPANIES, licenseTypes: INITIAL_LICENSE_TYPES, licenseNames: INITIAL_LICENSE_NAMES,
  paymentLinks: INITIAL_PAYMENT_LINKS, alertThreshold: 60, licenseThresholds: {},
  menuPermissions: DEFAULT_MENU_PERMS, unitMenuPermissions: {}, notificationConfig: cfg
};
for (const [k, v] of Object.entries(settings)) out.push(`INSERT OR REPLACE INTO settings (key, value) VALUES (${q(k)}, ${json(v)});`);

INITIAL_USERS.forEach((u, i) => {
  out.push(
    `INSERT OR IGNORE INTO users (id, login_id, name, emp_id, dept, desig, role, units, unit_roles, menus, pw_hash, created_at) VALUES (` +
    `${q(u.id)}, ${q(u.loginId || u.id)}, ${q(u.name)}, ${q(u.empId)}, ${q(u.dept)}, ${q(u.desig)}, ${q(u.role)}, ${json(u.units)}, ` +
    `${u.unitRoles ? json(u.unitRoles) : 'NULL'}, ${u.menus ? json(u.menus) : 'NULL'}, NULL, ${1700000000000 + i});`
  );
});

for (const l of INITIAL_LICENSES) {
  out.push(
    `INSERT OR IGNORE INTO licenses (id, company, type, name, till_date, status, locked, review_state, data, updated_at, updated_by) VALUES (` +
    `${q(l.id)}, ${q(l.company)}, ${q(l.type)}, ${q(l.name)}, ${q(l.till)}, ${q(l.status)}, ${l.locked ? 1 : 0}, ${q(l.reviewState)}, ${json(l)}, 1700000000000, 'seed');`
  );
}

const first = { id: 'seed_audit_01', ts: 1700000000000, user: 'System', action: 'System', entity: 'Database', entityId: 'Init', unit: 'All',
  summary: 'BLMS initialised with demo compliance data', changes: [] };
out.push(`INSERT OR IGNORE INTO audit_log (k, ts, data) VALUES (${q(first.id)}, ${first.ts}, ${json(first)});`);
out.push('COMMIT;', '');

const file = path.resolve(process.cwd(), 'database/seed.sql');
fs.writeFileSync(file, out.join('\n'));
console.log(`Wrote ${file} (${INITIAL_USERS.length} users, ${INITIAL_LICENSES.length} licenses)`);
